async function main() {
  await mongoose.connect(MONGO_URI, {
    useNewUrlParser: true,
    useUnifiedTopology: true,
    useCreateIndex: true,
    useFindAndModify: false,
  });
  console.log('Connected →', MONGO_URI);

  for (const row of DEMO_CASES) {
    const { serial } = row;
    const existing = await Transfer.findOne({ serial });
    if (existing) {
      await Transfer.updateOne({ serial }, { $set: row });
      console.log('更新', serial, row.hospitalName);
    } else {
      await Transfer.create(row);
      console.log('新增', serial, row.hospitalName);
    }
  }

  const total = await Transfer.countDocuments();
  console.log(`\n完成。CC_DB.transfers 共 ${total} 筆（含 demo ${DEMO_CASES.length} 筆）`);
  await mongoose.disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
